"""
Publication-grade Markdown scientific dossier generator for peptide characterization and mutational screening.
"""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional, Union

from insilico_peptide.core.biophysics import PeptideProperties
from insilico_peptide.screening.alanine_scan import MutantProfile


def generate_markdown_dossier(
    properties: PeptideProperties,
    name: Optional[str] = None,
    mutants: Optional[List[MutantProfile]] = None,
    multi_omics: Optional[Dict[str, Any]] = None,
) -> str:
    """
    Generate an academic-grade Markdown dossier.

    Args:
        properties: Computed biophysical profile.
        name: Common name of peptide (e.g. 'GLP-1(7-36)', 'BPC-157').
        mutants: Optional mutational scan candidate profiles.
        multi_omics: Optional UniProt/AlphaFold/ChEMBL metadata.

    Returns:
        Formatted Markdown dossier string.
    """
    peptide_name = name or properties.sequence
    now_utc = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    lines: List[str] = [
        f"# In-Silico Biophysical Dossier: {peptide_name}",
        "",
        "**Generated by:** `insilico-peptide-toolkit` (@Juanj053)  ",
        f"**Date:** {now_utc}  ",
        f"**Sequence:** `{properties.sequence}`  ",
        f"**Length:** {properties.length} amino acids  ",
        f"**pKa Scale Applied:** {properties.pka_scale}  ",
        "",
        "---",
        "",
        "## 1. Executive Biophysical Summary",
        "",
        "| Metric | Value | Classification / Interpretation |",
        "|---|---|---|",
        f"| **Average Molecular Weight** | {properties.molecular_weight:.2f} Da | Standard isotopic composition |",
        f"| **Monoisotopic Mass** | {properties.monoisotopic_mass:.4f} Da | High-resolution mass spectrometry standard |",
        f"| **Isoelectric Point (pI)** | {properties.isoelectric_point:.2f} | Bisection root finding (|Q| < 10⁻⁵) |",
        f"| **Net Charge at pH 7.4** | {properties.charge_at_ph_7_4:+.2f} e | Physiological pH electrostatic state |",
        f"| **Net Charge at pH 7.0** | {properties.charge_at_ph_7_0:+.2f} e | Neutral solution electrostatic state |",
        f"| **GRAVY Hydropathicity** | {properties.gravy:+.4f} | {'Net Hydrophobic' if properties.gravy > 0 else 'Net Hydrophilic (Aqueous Soluble)'} |",
        f"| **Amphiphilic Moment (μ_H, α-helix)** | {properties.hydrophobic_moment:.4f} | {'High Amphiphilicity (Membrane/Receptor Interface)' if properties.hydrophobic_moment > 0.15 else 'Moderate/Low Amphiphilicity'} |",
        f"| **Guruprasad Instability Index (II)** | {properties.instability_index:.2f} | **{'Stable (t₁/₂ > 16h)' if properties.is_stable else 'Unstable (t₁/₂ < 5h)'}** |",
        f"| **Aliphatic Index (AI)** | {properties.aliphatic_index:.2f} | Thermostability index (Ikai 1980) |",
        f"| **Enzymatic Vulnerability Score** | {properties.vulnerability_score:.4f} | Cleavage sites per residue ratio |",
        "",
        "---",
        "",
        "## 2. Proteolytic Cleavage Susceptibility Map",
        "",
        "| Endopeptidase | Cleavage Sites (1-based cut positions) | Resulting Predicted Fragments |",
        "|---|---|---|",
    ]

    for protease, sites in properties.proteolytic_cleavage_sites.items():
        sites_str = ", ".join(str(s) for s in sites) if sites else "*None (Enzymatically resistant)*"
        frags = properties.fragments.get(protease, [properties.sequence])
        frags_str = " + ".join(f"`{f}`" for f in frags) if frags else f"`{properties.sequence}`"
        lines.append(f"| **{protease.upper()}** | {sites_str} | {frags_str} |")

    if mutants:
        lines.extend([
            "",
            "---",
            "",
            "## 3. In-Silico Mutational Screening & Hotspot Profile",
            "",
            "| Pos | Mutation | ΔMW (Da) | ΔpI | ΔGRAVY | Δμ_H | ΔII | ΔQ(7.4) | ΔΔG (kcal/mol) | ΔSol | Pareto Rank | Hotspot Status |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|",
        ])

        for m in mutants:
            hotspot_tag = "🔴 **HOTSPOT**" if m.is_hotspot else "⚪ Neutral"
            reasons_str = f" ({'; '.join(m.hotspot_reasons)})" if m.is_hotspot else ""
            lines.append(
                f"| {m.position} | `{m.wt_residue}{m.position}{m.mut_residue}` | "
                f"{m.delta_mw:+.2f} | {m.delta_pi:+.2f} | {m.delta_gravy:+.4f} | "
                f"{m.delta_moment:+.4f} | {m.delta_instability:+.2f} | {m.delta_charge:+.2f} | "
                f"{m.ddg_pred:+.2f} | {m.solubility_pred:+.2f} | **Rank {m.pareto_rank}** | {hotspot_tag}{reasons_str} |"
            )

    if multi_omics:
        lines.extend([
            "",
            "---",
            "",
            "## 4. Multi-Omic Database Correlation",
            "",
        ])
        if "uniprot" in multi_omics:
            u = multi_omics["uniprot"]
            lines.extend([
                f"- **UniProt KB:** Accession `{u.get('accession')}` ({u.get('entry_name')})",
                f"  - Protein: {u.get('protein_name')}",
                f"  - Gene: `{u.get('gene_name')}` | Organism: *{u.get('organism')}*",
            ])
        if "alphafold" in multi_omics:
            af = multi_omics["alphafold"]
            lines.extend([
                f"- **AlphaFold Structure DB:** Entry `{af.get('entry_id')}`",
                f"  - Mean pLDDT Confidence: **{af.get('mean_plddt'):.2f}**",
                f"  - PDB Download: [Download PDB]({af.get('pdb_url')})",
            ])
        if "chembl" in multi_omics:
            ch = multi_omics["chembl"]
            lines.extend([
                f"- **ChEMBL Target:** `{ch.get('target_chembl_id')}` — *{ch.get('pref_name')}*",
                f"  - Target Type: {ch.get('target_type')} | Organism: *{ch.get('organism')}*",
            ])

    lines.extend([
        "",
        "---",
        "",
        "## 5. Algorithmic Provenance & Scientific References",
        "",
        "1. **Isoelectric Point & Charge:** Henderson-Hasselbalch equation via bisection root finding on EMBOSS / Bjellqvist scales (Rice et al., 2000; Bjellqvist et al., 1993).",
        "2. **Hydropathicity:** Kyte-Doolittle consensus hydropathy index (Kyte & Doolittle, *J. Mol. Biol.* 1982, 157:105-132).",
        "3. **Hydrophobic Moment:** Eisenberg 2D vector Fourier transform for periodic amphiphilicity (Eisenberg et al., *Nature* 1982, 299:371-374; *PNAS* 1984, 81:140-144).",
        "4. **Instability Index:** Guruprasad dipeptide instability matrix weights with 40.0 stability threshold (Guruprasad et al., *Protein Eng.* 1990, 4:155-161).",
        "5. **Aliphatic Index:** Relative volume of aliphatic side chains (Ikai, *J. Biochem.* 1980, 88:1895-1898).",
        "",
        "*Dossier generated automatically by `insilico-peptide-toolkit`.*",
    ])

    return "\n".join(lines) + "\n"


def export_to_markdown(
    properties: PeptideProperties,
    output_path: Union[str, Path],
    name: Optional[str] = None,
    mutants: Optional[List[MutantProfile]] = None,
    multi_omics: Optional[Dict[str, Any]] = None,
) -> None:
    """
    Write Markdown dossier directly to disk.

    Args:
        properties: Computed biophysical profile.
        output_path: Target path for the Markdown file.
        name: Optional peptide name.
        mutants: Optional list of mutant profiles.
        multi_omics: Optional multi-omic dictionary.
    """
    content = generate_markdown_dossier(properties, name=name, mutants=mutants, multi_omics=multi_omics)
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
